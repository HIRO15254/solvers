"""Write a B4 Simple config whose preflop menus equal GTO Wizard's at the nodes of the tree reference.

usage: python gtow_tree.py <base config TOML> <output TOML>

The base is examples/bench/6max_100bb_nl50_partial_simple_reference.toml, which reproduces only the opening and
vs-open menus (later raises are 2.5x and raises above a third of the stack become all-in). For every node of the
reference (GTO Wizard's preflop nodes with line probability >= 0.0005) this appends a rule that matches the node by
actor position, aggressions, players, last raiser, pot and amount to call, and sets GTO Wizard's raise sizes,
all-in and call. The rules come after the base rules, so they win; nodes below the reference's line-probability
cut keep the base rules. The reraise-to-all-in conversion is moved from 1/3 to 1/2 of the stack, because GTO Wizard
4bets to 40-43 bb. The predicates cannot tell an UTG open from an HJ open once the other has folded, and GTO Wizard
sizes 7 such pairs of nodes 1-3 bb apart; the more likely node's menu is used for both and the pairs are printed.
"""
import json
import re
import sys
from pathlib import Path

REFERENCE = Path(__file__).resolve().parent / "references/gtowizard-simple-100bb-preflop-tree-2026-10-09.json"
ORDER = ["UTG", "HJ", "CO", "BTN", "SB", "BB"]
STACK = 100.0


def state(history):
    """(actor, aggressions, players, last raiser, pot, to_call) before the next action of a GTO Wizard history."""
    wager = {p: 0.0 for p in ORDER}
    wager["SB"], wager["BB"] = 0.5, 1.0
    folded = set()
    aggressions = 0
    last = ""
    turn = 0
    for code in history:
        while ORDER[turn % 6] in folded:
            turn += 1
        actor = ORDER[turn % 6]
        if code == "F":
            folded.add(actor)
        elif code == "C":
            wager[actor] = max(wager.values())
        else:
            wager[actor] = STACK if code == "RAI" else float(code[1:])
            aggressions += 1
            last = actor
        turn += 1
    while ORDER[turn % 6] in folded:
        turn += 1
    actor = ORDER[turn % 6]
    pot = sum(wager.values())
    return actor, aggressions, 6 - len(folded), last, pot, max(wager.values()) - wager[actor]


def size(x):
    return f"{x:g}bb"


def rule(node):
    actor, aggressions, players, last, pot, to_call = state(node["history"])
    assert actor == node["actor"], (node["history"], actor)
    codes = [a["code"] for a in node["actions"]]
    raises = [size(float(c[1:])) for c in codes if c.startswith("R") and c != "RAI"]
    if "RAI" in codes:
        raises.append("a")
    condition = (f'aggressions == {aggressions} && players == {players} && position == "{actor}" && '
                 f'last_preflop_aggressor_position == "{last}" && pot > {pot - 0.05:.2f} && pot < {pot + 0.05:.2f} && '
                 f'to_call > {to_call - 0.05:.2f} && to_call < {to_call + 0.05:.2f}')
    body = []
    body.append(f"replace raise [{', '.join(raises)}]" if raises else "remove raise")
    if to_call > 0:
        body.append("add call []" if "C" in codes else "remove call")
    key = (actor, aggressions, players, last, round(pot, 2), round(to_call, 2))
    return key, tuple(codes), f"preflop when {condition} {{ {'  '.join(body)} }}"


def main(base, output):
    reference = json.loads(REFERENCE.read_text(encoding="utf-8"))
    text = Path(base).read_text(encoding="utf-8")
    seen = {}
    lines = []
    # The reference lists nodes by decreasing line probability, so the first menu of a key is the likelier one.
    for node in reference["nodes"]:
        key, menu, line = rule(node)
        if key in seen:
            if seen[key] != menu:
                print(f"indistinguishable: {'-'.join(node['history'])} {menu} uses {seen[key]}")
            continue
        seen[key] = menu
        lines.append(line)
    marker = "flop, turn, river when players >= 2 { replace bet [50, a] }"
    assert marker in text
    generated = "# GTO Wizard Simple 100bb menus at the reference's nodes (gtow_tree.py)\n" + "\n".join(lines) + "\n"
    text = text.replace(marker, generated + marker, 1)
    text, n = re.subn(r"\[tree\.preflop_reraise_jam_above_stack\]\ndenominator = 3\nnumerator = 1",
                      "[tree.preflop_reraise_jam_above_stack]\ndenominator = 2\nnumerator = 1", text)
    assert n == 1
    text = text.replace("# Six-max 100-BB NL50 workload reproducing the simpler observed reference action menus.",
                        "# Six-max 100-BB NL50: B4 Simple with GTO Wizard Simple's preflop menus at the 135 nodes of the\n"
                        "# 2026-10-09 tree reference (generated by experiments/p2-method-2026-10/b4s-8h/gtow_tree.py).", 1)
    Path(output).write_text(text, encoding="utf-8")
    print(f"{len(lines)} rules -> {output}")


if __name__ == "__main__":
    main(*sys.argv[1:])
