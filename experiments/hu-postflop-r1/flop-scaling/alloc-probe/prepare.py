"""Exact research-only allocator instrumentation; never edits the base adapter."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE = HERE.parent / "native-solve" / "solve.rs"
BASE_SHA256 = "547ed17705b7784ac656fb8032d859261b9a4639fa49dc0ba4b105cdfe2addd9"
BASE_BYTES = 11148
OLD_EVENT = b'''fn event(phase: &str, status: &str) {
    println!("{{\\"phase\\":\\"{phase}\\",\\"status\\":\\"{status}\\"}}");
    std::io::stdout().flush().unwrap();
}
'''
NEW_EVENT = b'''fn event(phase: &str, status: &str) {
    if status == "completed" {
        if let Some(counts) = allocation_probe::stop() {
            allocation_probe::emit(phase, counts);
        }
    }
    println!("{{\\"phase\\":\\"{phase}\\",\\"status\\":\\"{status}\\"}}");
    std::io::stdout().flush().unwrap();
    if status == "started" {
        allocation_probe::start();
    }
}
'''
ANCHOR = b"use std::collections::{BTreeMap, BTreeSet};\n"


def pin(raw: bytes) -> dict:
    return {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}


def transform(base: bytes, allocator: bytes) -> bytes:
    if pin(base) != {"bytes": BASE_BYTES, "sha256": BASE_SHA256}:
        raise ValueError("base adapter exact pin mismatch")
    # Work on LF text but preserve the original remainder's byte representation.
    newline = b"\r\n" if b"\r\n" in base else b"\n"
    old_event = OLD_EVENT.replace(b"\n", newline)
    anchor = ANCHOR.replace(b"\n", newline)
    if base.count(old_event) != 1 or base.count(anchor) != 1:
        raise ValueError("expected unique transformation anchors")
    if b"allocation_probe" in base or b"#[global_allocator]" in base:
        raise ValueError("base already instrumented")
    allocator = allocator.replace(b"\r\n", b"\n").rstrip(b"\n") + b"\n\n"
    return base.replace(old_event, NEW_EVENT.replace(b"\n", newline)).replace(
        anchor, allocator.replace(b"\n", newline) + anchor
    )


def expected() -> tuple[dict[str, bytes], dict]:
    base = BASE.read_bytes()
    allocator = (HERE / "allocator.rs.in").read_bytes()
    body = (HERE / "selftest-body.rs.in").read_bytes()
    generated = {
        "probe.rs": transform(base, allocator),
        "selftest.rs": allocator.rstrip(b"\r\n") + b"\n\n" + body,
    }
    inputs = {"../native-solve/solve.rs": pin(base)}
    for name in ("prepare.py", "allocator.rs.in", "selftest-body.rs.in"):
        inputs[name] = pin((HERE / name).read_bytes())
    provenance = {
        "schema": "r1-allocation-probe-transform/v1",
        "inputs": inputs,
        "generated": {name: pin(raw) for name, raw in generated.items()},
        "edits": ["insert allocator module before first std import", "replace event function only"],
        "unchanged_contract": "same fixture, arguments, CFR, public quality APIs and full state writer",
        "metrics": "process allocator operations admitted during each phase; requested bytes are not live memory or RSS",
        "counter_limit": "u64 modulo arithmetic; finite bounded probe must remain below 2^64 operations and bytes per phase",
        "native_execution_claim": None,
    }
    return generated, provenance


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify existing generated bytes without writing")
    args = parser.parse_args()
    generated, provenance = expected()
    generated["provenance.json"] = (json.dumps(provenance, indent=2, sort_keys=True) + "\n").encode()
    for name, raw in generated.items():
        path = HERE / name
        if args.check:
            if path.read_bytes() != raw:
                raise ValueError(f"generated file differs: {name}")
        else:
            path.write_bytes(raw)
    print(json.dumps({"checked" if args.check else "generated": {name: pin(raw) for name, raw in generated.items()}}, sort_keys=True))


if __name__ == "__main__":
    main()
